/**
 * 提取文本中的纯汉字
 */
function extractChineseChars(text) {
    var chars = [];
    for (var i = 0; i < text.length; i++) {
        var code = text.charCodeAt(i);
        if (code >= 0x4E00 && code <= 0x9FFF) {
            chars.push(text[i]);
        }
    }
    return chars;
}

/**
 * 将文本按标点分割为句子
 */
function splitSentences(text) {
    var sentences = text.split(/[，。！？、；：""''（）《》【】\s,.!?;:'"()\[\]{}<>\n\r]+/);
    var result = [];
    for (var i = 0; i < sentences.length; i++) {
        var s = sentences[i].trim();
        if (s.length > 0) {
            result.push(s);
        }
    }
    return result;
}

// ==================== 维度一：语义 → 情感色彩 ====================

/**
 * 对单个字进行情感分类（增强版）
 * 支持上下文感知：传入前后字可提高准确度
 * 返回: 'tender' | 'lively' | 'natural' | 'calm' | 'neutral'
 */
function classifyCharEmotion(char, prevChar, nextChar) {
    // 1. 优先检查双字词组匹配（前后组合）
    if (prevChar) {
        var phrase1 = prevChar + char;
        var phraseEmotion1 = _matchPhrase(phrase1);
        if (phraseEmotion1) return phraseEmotion1;
    }
    if (nextChar) {
        var phrase2 = char + nextChar;
        var phraseEmotion2 = _matchPhrase(phrase2);
        if (phraseEmotion2) return phraseEmotion2;
    }

    // 2. 单字词典匹配
    if (SENTIMENT_DICT.tender.indexOf(char) !== -1) return 'tender';
    if (SENTIMENT_DICT.lively.indexOf(char) !== -1) return 'lively';
    if (SENTIMENT_DICT.natural.indexOf(char) !== -1) return 'natural';
    if (SENTIMENT_DICT.calm.indexOf(char) !== -1) return 'calm';
    if (SENTIMENT_DICT.neutral_words.indexOf(char) !== -1) return 'neutral';

    // 3. 意象色彩词典匹配（从weave-renderer中的IMAGE_COLOR_DICT推断情感）
    if (typeof IMAGE_COLOR_DICT !== 'undefined' && IMAGE_COLOR_DICT[char]) {
        var imgHsl = _hexToHsl ? _hexToHsl(IMAGE_COLOR_DICT[char]) : null;
        if (imgHsl) {
            return _hslToEmotionCategory(imgHsl.h, imgHsl.s, imgHsl.l);
        }
    }

    // 4. 基于偏旁部首推测情感（汉字结构蕴含语义信息）
    var radicalEmotion = _guessEmotionByRadical(char);
    if (radicalEmotion) return radicalEmotion;

    // 5. 未匹配的字，根据Unicode编码做确定性分配（偏向中性）
    var code = char.charCodeAt(0);
    // 让未匹配的字更倾向于中性，避免随机色彩干扰
    var types = ['neutral', 'neutral', 'tender', 'natural', 'calm'];
    return types[code % 5];
}

/**
 * 在双字词组词典中查找匹配
 */
function _matchPhrase(phrase) {
    if (typeof SENTIMENT_PHRASES === 'undefined') return null;
    for (var key in SENTIMENT_PHRASES) {
        if (SENTIMENT_PHRASES[key].indexOf(phrase) !== -1) {
            return key;
        }
    }
    return null;
}

/**
 * 根据HSL色值推断情感类别
 */
function _hslToEmotionCategory(h, s, l) {
    // 低饱和度 → 冷静/中性
    if (s < 0.2) return l > 0.6 ? 'neutral' : 'calm';
    // 红色系(330-30) → 温柔
    if ((h >= 330 || h < 30) && s > 0.3) return 'tender';
    // 橙黄色系(30-75) → 活泼
    if (h >= 30 && h < 75) return 'lively';
    // 绿色系(75-165) → 自然
    if (h >= 75 && h < 165) return 'natural';
    // 蓝紫色系(165-330) → 冷静
    if (h >= 165 && h < 270) return 'calm';
    // 紫红色系(270-330) → 温柔
    if (h >= 270 && h < 330) return 'tender';
    return 'neutral';
}

