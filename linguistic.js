/**
 * 对整段文本做情感分析（增强版）
 * 支持双字词组匹配和上下文感知
 * 返回每个汉字的情感分类和对应颜色
 */
function analyzeSemanticDimension(chineseChars) {
    var result = [];
    var emotionCounts = { tender: 0, lively: 0, natural: 0, calm: 0, neutral: 0 };

    for (var i = 0; i < chineseChars.length; i++) {
        var c = chineseChars[i];
        var prevChar = i > 0 ? chineseChars[i - 1] : null;
        var nextChar = i < chineseChars.length - 1 ? chineseChars[i + 1] : null;
        var emotion = classifyCharEmotion(c, prevChar, nextChar);
        emotionCounts[emotion]++;
        // 每个字对应一个情感颜色（从该情感的调色板中选取）
        var palette = EMOTION_COLORS[emotion].colors;
        var colorIdx = i % palette.length;
        result.push({
            char: c,
            emotion: emotion,
            color: palette[colorIdx],
            // 压点数量：情感词汇匹配度越高，压点越多
            pressPoints: getSemanticPressPoints(c, emotion)
        });
    }

    // 计算主导情感
    var dominant = 'neutral';
    var maxCount = 0;
    for (var key in emotionCounts) {
        if (emotionCounts[key] > maxCount) {
            maxCount = emotionCounts[key];
            dominant = key;
        }
    }

    return {
        charData: result,
        emotionCounts: emotionCounts,
        dominant: dominant
    };
}

